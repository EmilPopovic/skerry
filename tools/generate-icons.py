"""Compile the reviewed icon records; no SVG library or build-time dependency.

Run after editing crates/sk-ui/icons/designs.json or commands.json.
The HTML study is deliberately not part of this generator or the repository.
"""
import json
import re
import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "crates/sk-ui/icons"
DESIGNS = json.loads((SOURCE / "designs.json").read_text())
COMMANDS = json.loads((SOURCE / "commands.json").read_text())
LEGACY = {
    "folder": "Folder", "home": "GoHome", "folder-home": "Home", "folder-desktop": "Desktop",
    "folder-documents": "Documents", "folder-downloads": "Downloads",
    "folder-music": "Music", "folder-pictures": "Pictures", "folder-videos": "Videos",
    "folder-templates": "Templates", "folder-public": "Public",
    "file-unknown": "Unknown", "file-text": "Text", "file-document": "Document",
    "file-code": "Code", "file-image": "Image", "file-audio": "Audio",
    "file-video": "Video", "file-archive": "Archive", "file-spreadsheet": "Spreadsheet",
    "file-presentation": "Presentation", "file-font": "Font", "file-executable": "Executable",
    "file-disk-image": "DiskImage", "file-web": "Web", "source": "Source",
    "folder-project": "Project", "removable": "Removable",
}


def variant(id):
    return LEGACY.get(id, "".join(part.title() for part in id.split("-")))


def number(value):
    return f"{float(value):.6f}".rstrip("0").rstrip(".") + (
        ".0" if float(value).is_integer() else ""
    )


def transform(text, parent):
    sx, sy, tx, ty = parent
    for name, args in re.findall(r"(\w+)\(([^)]*)\)", text):
        values = [float(v) for v in re.split(r"[, ]+", args.strip())]
        if name == "translate":
            tx += sx * values[0]
            ty += sy * (values[1] if len(values) > 1 else 0)
        elif name == "scale":
            sx *= values[0]
            sy *= values[-1]
        else:
            raise ValueError(f"unsupported transform: {name}")
    return sx, sy, tx, ty


def path(element):
    a = element.attrib
    if element.tag == "path":
        return a["d"]
    if element.tag in ("circle", "ellipse"):
        x, y = float(a["cx"]), float(a["cy"])
        rx, ry = float(a.get("rx", a.get("r", 0))), float(a.get("ry", a.get("r", 0)))
        return f"M{x-rx} {y}a{rx} {ry} 0 1 0 {rx*2} 0a{rx} {ry} 0 1 0 {-rx*2} 0Z"
    if element.tag == "rect":
        x, y, w, h = (float(a[n]) for n in ("x", "y", "width", "height"))
        rad = min(float(a.get("rx", 0)), w / 2, h / 2)
        if not rad:
            return f"M{x} {y}h{w}v{h}h{-w}Z"
        return (f"M{x+rad} {y}h{w-2*rad}a{rad} {rad} 0 0 1 {rad} {rad}"
                f"v{h-2*rad}a{rad} {rad} 0 0 1 {-rad} {rad}h{-w+2*rad}"
                f"a{rad} {rad} 0 0 1 {-rad} {-rad}v{-h+2*rad}"
                f"a{rad} {rad} 0 0 1 {rad} {-rad}Z")
    raise ValueError(element.tag)


def paints(element, matrix=(1, 1, 0, 0), inherited=None):
    attrs = dict(inherited or {"fill": "none", "stroke": "currentColor", "stroke-width": "1.65"})
    attrs.update(element.attrib)
    matrix = transform(element.get("transform", ""), matrix)
    if element.tag in ("svg", "g"):
        for child in element:
            yield from paints(child, matrix, attrs)
        return
    d = path(element)
    fill = attrs.get("fill", "none")
    if fill != "none":
        layer = 0 if fill.startswith("var(") else 1 if float(attrs.get("fill-opacity", "1")) < 1 else 2
        yield d, matrix, 0, False, layer
    if attrs.get("stroke") != "none":
        yield d, matrix, float(attrs["stroke-width"]), "stroke-dasharray" in attrs, 2


def generate():
    header = "// SPDX-License-Identifier: Apache-2.0\n// Generated by tools/generate-icons.py; edit crates/sk-ui/icons/designs.json.\n"
    data = header + "use super::Paint;\n\npub(super) const SYMBOLS: &[&[Paint]] = &[\n"
    names = []
    for icon in DESIGNS:
        names.append(variant(icon["id"]))
        data += f'    // {icon["id"]}\n    &[\n'
        for d, matrix, width, dash, layer in paints(ET.fromstring("<svg>" + icon["art"] + "</svg>")):
            matrix = ", ".join(map(number, matrix))
            data += f'        Paint {{ path: {json.dumps(d)}, transform: [{matrix}], width: {number(width)}, dashed: {str(dash).lower()}, layer: {layer} }},\n'
        data += "    ],\n"
    data += "];\n"
    assert len(set(names)) == len(names)
    (ROOT / "crates/sk-text/src/symbols_data.rs").write_text(data)
    enum = header + "//! The bundled content and action icon family.\n\nuse sk_gpu::{Color, DrawList, Rect};\n\n/// A bundled file, place, status or action symbol.\n#[derive(Clone, Copy, PartialEq, Eq, Debug, Hash)]\n#[repr(u16)]\npub enum Mark {\n"
    for i, icon in enumerate(DESIGNS):
        enum += f'    /// {icon["label"]}.\n    {names[i]} = {i},\n'
    enum += "}\n\nimpl Mark {\n    /// Every bundled symbol in specimen order.\n"
    enum += f'    pub const ALL: [Self; {len(names)}] = [\n' + "".join(f"        Self::{n},\n" for n in names) + "    ];\n"
    enum += '    /// Stable asset identifier, independent of translation.\n    #[must_use]\n    #[allow(clippy::too_many_lines, reason = \"generated exhaustive asset identifiers\")]\n    pub const fn name(self) -> &\'static str {\n        match self {\n'
    enum += "".join(f'            Self::{names[i]} => "{d["id"]}",\n' for i, d in enumerate(DESIGNS)) + "        }\n    }\n"
    folders = [names[i] for i, d in enumerate(DESIGNS) if d["group"] == "Folders"]
    enum += '    /// Whether this symbol represents a directory.\n    #[must_use]\n    pub const fn is_folder(self) -> bool {\n        matches!(self, ' + " | ".join(f"Self::{n}" for n in folders) + ")\n    }\n}\n"
    enum += '''
pub(crate) fn draw(list: &mut DrawList, mark: Mark, at: Rect, ink: Color, backing: Color) {
    let side = at.width.min(at.height);
    if side <= 0.0 || ink.is_invisible() { return; }
    let x = at.x + (at.width - side) * 0.5;
    let y = (at.y + (at.height - side) * 0.5).round();
    let quarter_px = (side * 4.0).round().clamp(1.0, 2048.0) as u16;
    let px_size = f32::from(quarter_px) / 4.0;
    let subpixel = (x.fract().rem_euclid(1.0) * 4.0).floor() as u8;
    let layers = sk_text::symbols::layers(mark as u16);
    for layer in 0..3u16 {
        if layers & (1 << layer) == 0 { continue; }
        let color = match layer {
            0 => backing.with_alpha(ink.components().3),
            1 => ink.with_alpha(ink.components().3 / 10),
            _ => ink,
        };
        let key = sk_text::GlyphKey {
            face: sk_text::symbols::FACE,
            glyph: mark as u16 * 3 + layer,
            quarter_px,
            subpixel,
        };
        list.glyph(key, x.floor(), y + px_size.ceil(), color);
    }
}
'''
    (ROOT / "crates/sk-ui/src/marks.rs").write_text(enum)
    commands = header.replace("designs.json", "commands.json")
    commands += "use sk_ui::Mark;\n\n#[allow(clippy::too_many_lines, reason = \"generated command-to-asset table\")]\n pub(crate) fn of_command(id: &str) -> Option<Mark> {\n    Some(match id {\n"
    aliases = dict(COMMANDS)
    aliases.update({"menu.open_in": "open", "menu.open_with": "open-with", "menu.colour": "color", "menu.view": "view-grid", "menu.sort": "sort-name", "menu.group": "group", "menu.templates": "new-file", "menu.index": "index", "menu.operation": "history", "menu.panes": "split-beside"})
    grouped = {}
    for id, symbol in sorted(aliases.items()):
        grouped.setdefault(symbol, []).append(id)
    for symbol, ids in grouped.items():
        pattern = " | ".join(json.dumps(id) for id in ids)
        commands += f'        {pattern} => Mark::{variant(symbol)},\n'
    commands += '        _ if id.starts_with("view.colour_") => Mark::Color,\n        _ => return None,\n    })\n}\n'
    (ROOT / "crates/sk-app/src/action_marks.rs").write_text(commands)
    subprocess.run(["cargo", "fmt", "--all"], cwd=ROOT, check=True)


if __name__ == "__main__":
    generate()
